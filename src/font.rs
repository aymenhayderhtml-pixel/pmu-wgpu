/// Builds a 128x64 RGBA8 font atlas containing the 95 ASCII glyphs in cells 0..95
/// and a solid white 8x8 block in cell 95 (`SOLID_WHITE_CELL`) for drawing solid quads.
pub fn build_font_atlas_rgba8() -> Vec<u8> {
    let mut rgba = vec![0u8; (ATLAS_WIDTH * ATLAS_HEIGHT * 4) as usize];

    for (cell_idx, glyph) in FONT_8X8.iter().enumerate() {
        write_cell(&mut rgba, cell_idx as u32, glyph);
    }

    let solid_block = [0xFFu8; 8];
    write_cell(&mut rgba, SOLID_WHITE_CELL, &solid_block);

    rgba
}

fn write_cell(rgba: &mut [u8], cell_idx: u32, rows: &[u8; 8]) {
    let col = cell_idx % ATLAS_COLS;
    let row = cell_idx / ATLAS_COLS;
    let base_x = col * GLYPH_SIZE;
    let base_y = row * GLYPH_SIZE;

    for (gy, &bits) in rows.iter().enumerate() {
        for gx in 0..8u32 {
            let mask = 0x80u8 >> gx;
            if (bits & mask) != 0 {
                let px = base_x + gx;
                let py = base_y + (gy as u32);
                let idx = ((py * ATLAS_WIDTH + px) * 4) as usize;
                rgba[idx] = 255;
                rgba[idx + 1] = 255;
                rgba[idx + 2] = 255;
                rgba[idx + 3] = 255;
            }
        }
    }
}

/// Returns `(u0, v0, u1, v1)` atlas UVs for an ASCII byte (or `'?'` if outside `32..=126`).
#[inline]
pub fn glyph_uv(byte: u8) -> (f32, f32, f32, f32) {
    let code = if (32..=126).contains(&byte) {
        u32::from(byte - 32)
    } else {
        u32::from(b'?' - 32)
    };
    cell_uv(code)
}

#[inline]
pub fn solid_white_uv() -> (f32, f32, f32, f32) {
    let (u0, v0, u1, v1) = cell_uv(SOLID_WHITE_CELL);
    let u_mid = (u0 + u1) * 0.5;
    let v_mid = (v0 + v1) * 0.5;
    (u_mid, v_mid, u_mid, v_mid)
}

#[inline]
fn cell_uv(cell_idx: u32) -> (f32, f32, f32, f32) {
    let col = cell_idx % ATLAS_COLS;
    let row = cell_idx / ATLAS_COLS;
    let u0 = (col * GLYPH_SIZE) as f32 / (ATLAS_WIDTH as f32);
    let v0 = (row * GLYPH_SIZE) as f32 / (ATLAS_HEIGHT as f32);
    let u1 = ((col + 1) * GLYPH_SIZE) as f32 / (ATLAS_WIDTH as f32);
    let v1 = ((row + 1) * GLYPH_SIZE) as f32 / (ATLAS_HEIGHT as f32);
    (u0, v0, u1, v1)
}
